-- SQL DDL starter for CourtConnect (simplified)
CREATE TABLE [Users] (
  Id UNIQUEIDENTIFIER PRIMARY KEY,
  UserName NVARCHAR(100) NOT NULL,
  DisplayName NVARCHAR(200),
  Email NVARCHAR(200),
  Phone NVARCHAR(50),
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE [Locations] (
  Id UNIQUEIDENTIFIER PRIMARY KEY,
  Name NVARCHAR(200),
  Address NVARCHAR(500),
  Latitude FLOAT NULL,
  Longitude FLOAT NULL
);

CREATE TABLE [Events] (
  Id UNIQUEIDENTIFIER PRIMARY KEY,
  Title NVARCHAR(200) NOT NULL,
  Description NVARCHAR(MAX),
  LocationId UNIQUEIDENTIFIER NULL,
  StartDate DATETIME2 NOT NULL,
  EndDate DATETIME2 NULL,
  MaxPlayers INT NULL,
  CreatedByUserId UNIQUEIDENTIFIER NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  IsPublic BIT NOT NULL DEFAULT 1,
  CONSTRAINT FK_Event_Location FOREIGN KEY (LocationId) REFERENCES Locations(Id),
  CONSTRAINT FK_Event_CreatedBy FOREIGN KEY (CreatedByUserId) REFERENCES Users(Id)
);

CREATE TABLE [RSVPs] (
  Id UNIQUEIDENTIFIER PRIMARY KEY,
  EventId UNIQUEIDENTIFIER NOT NULL,
  UserId UNIQUEIDENTIFIER NOT NULL,
  Status NVARCHAR(20) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_RSVP_Event FOREIGN KEY (EventId) REFERENCES Events(Id),
  CONSTRAINT FK_RSVP_User FOREIGN KEY (UserId) REFERENCES Users(Id)
);
